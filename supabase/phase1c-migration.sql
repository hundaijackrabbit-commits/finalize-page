  add column if not exists processing_completed_at timestamptz;

create table if not exists public.processing_jobs (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  finalization_id uuid not null references public.finalizations(id) on delete cascade,
  artifact_id uuid not null references public.artifacts(id) on delete cascade,
  job_type text not null,
  status public.processing_job_status not null default 'QUEUED',
  priority integer not null default 100,
  attempts integer not null default 0,
  max_attempts integer not null default 4,
  available_at timestamptz not null default now(),
  lease_until timestamptz,
  worker_id text,
  input jsonb not null default '{}'::jsonb,
  output jsonb not null default '{}'::jsonb,
  last_error text,
  started_at timestamptz,
  completed_at timestamptz,
  dead_lettered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (artifact_id, job_type)
);

create index if not exists processing_jobs_claim_idx
  on public.processing_jobs(status, available_at, priority, created_at)
  where status in ('QUEUED','RETRY');
create index if not exists processing_jobs_artifact_idx on public.processing_jobs(artifact_id, created_at);

