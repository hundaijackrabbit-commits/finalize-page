-- Atomic job claiming prevents two workers from processing the same job.
create or replace function public.claim_finalize_processing_job(p_worker_id text, p_lease_seconds integer default 120)
returns setof public.processing_jobs
language plpgsql
security definer set search_path = public
as $$
declare
  picked uuid;
begin
  select id into picked
  from public.processing_jobs
  where (
      status in ('QUEUED','RETRY')
      and available_at <= now()
    ) or (
      status = 'RUNNING'
      and lease_until is not null
      and lease_until < now()
    )
  order by priority asc, available_at asc, created_at asc
  for update skip locked
  limit 1;

  if picked is null then
    return;
  end if;

  return query
  update public.processing_jobs
  set status = 'RUNNING',
      attempts = attempts + 1,
      worker_id = p_worker_id,
      lease_until = now() + make_interval(secs => greatest(30, p_lease_seconds)),
      started_at = coalesce(started_at, now()),
      updated_at = now()
  where id = picked
  returning *;
end;
$$;

revoke all on function public.claim_finalize_processing_job(text, integer) from public;
grant execute on function public.claim_finalize_processing_job(text, integer) to service_role;
