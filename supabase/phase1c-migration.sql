create index if not exists artifact_privacy_findings_artifact_idx on public.artifact_privacy_findings(artifact_id);

create table if not exists public.artifact_processing_events (
  id bigint generated by default as identity primary key,
  organization_id uuid not null references public.organizations(id) on delete cascade,
  finalization_id uuid not null references public.finalizations(id) on delete cascade,
